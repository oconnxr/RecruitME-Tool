// Builds apps-script/Dashboard.html from the dashboard page plus the
// scoring and Sheet code, so the Sheets dashboard ranks exactly like the CLI.
// Run: npm run build:apps-script
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadConfig } from "../src/board.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const unexport = (src) => {
  if (/^import /m.test(src)) throw new Error("Inlined modules must not have imports.");
  return src.replace(/^export /gm, "");
};

// Benchmarks and weights only; the agent settings aren't needed in the page.
const { ranking, benchmarks } = loadConfig(path.join(ROOT, "config", "__none__.json"));
const inline = `<script>
(function () {
const CONFIG = ${JSON.stringify({ ranking, benchmarks })};
${unexport(read("src/scoring.js"))}
${unexport(read("src/sheet.js"))}
window.__BOARD_LOADER__ = function () {
  return new Promise(function (resolve, reject) {
    google.script.run
      .withSuccessHandler(function (d) {
        resolve({
          prospects: rankBoard(fromSheetTable(d.rows), CONFIG, { includeCommitted: true }),
          programName: d.programName,
          lastUpdate: d.lastUpdate,
        });
      })
      .withFailureHandler(reject)
      .getBoardData();
  });
};
})();
</script>`.replace(/<\/script>(?!$)/g, "<\\/script>");

const page = read("public/index.html").replace("<!--BOARD-->", () => inline);
const out = path.join(ROOT, "apps-script", "Dashboard.html");
fs.writeFileSync(out, "<!-- Generated by scripts/build-apps-script.js. Edit public/index.html, src/scoring.js or config, then rebuild. -->\n" + page);
console.log(`Wrote ${path.relative(ROOT, out)} (${Math.round(fs.statSync(out).size / 1024)} KB)`);
